#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn thresholds_are_strictly_increasing_and_end_at_max() {
		assert_eq!(THRESHOLDS[0], EXISTENTIAL_WEIGHT);
		assert!(THRESHOLDS.windows(2).all(|w| w[0] < w[1]));
		assert_eq!(*THRESHOLDS.last().unwrap(), VoteWeight::MAX);
	}

	/// A stake's bag, at an issuance a factor tied to it would step at.
	fn bag_of(stake: crate::Balance) -> VoteWeight {
		use sp_staking::currency_to_vote::CurrencyToVote;
		let issuance = u64::MAX as u128 * 10u128.pow(8) + 1;
		let weight = super::super::vote::DecimalCurrencyToVote::to_vote(stake, issuance);
		pallet_bags_list::notional_bag_for::<crate::Runtime, pallet_bags_list::Instance1>(weight)
	}

	#[test]
	fn the_minimum_bonds_land_in_the_expected_bags() {
		use super::super::vote::VOTE_FACTOR;
		use crate::{primitives::constants::ORB, staking::params::*};
		let first = 10 * ORB;
		assert_eq!(bag_of(first), THRESHOLDS[0]);
		assert_eq!(bag_of(first - 1), THRESHOLDS[0]);
		assert_eq!(bag_of(first + VOTE_FACTOR - 1), THRESHOLDS[0]);
		assert_eq!(bag_of(first + VOTE_FACTOR), THRESHOLDS[1]);
		// Ten times the first, ⌈log(10) / log(1.1132)⌉ = 22 bags up.
		for bond in [
			TEST_MIN_NOMINATOR_BOND,
			MAINNET_MIN_NOMINATOR_BOND,
			TEST_POOL_MIN_CREATE_BOND,
		] {
			assert_eq!(bag_of(bond), THRESHOLDS[22]);
		}
	}
}
